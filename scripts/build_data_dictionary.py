#!/usr/bin/env python3
"""Generate docs/DATA_DICTIONARY.md from the dbt YAML (via target/manifest.json).

    python scripts/build_data_dictionary.py           # write the file
    python scripts/build_data_dictionary.py --check   # fail if it is out of date

The YAML is the single source of truth for descriptions, data types and tests;
this script only renders it, so the dictionary cannot drift from the models.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "docs" / "DATA_DICTIONARY.md"
LAYERS = [("staging", "Staging"), ("marts/core", "Marts: core"), ("marts/finance", "Marts: finance")]


def column_tests(manifest: dict) -> dict[tuple[str, str], list[str]]:
    """Map (model unique_id, column) -> short test names."""
    tests: dict[tuple[str, str], list[str]] = {}
    for node in manifest["nodes"].values():
        if node["resource_type"] != "test" or not node.get("column_name"):
            continue
        meta = node.get("test_metadata") or {}
        name = meta.get("name", node["name"])
        if meta.get("namespace"):
            name = f"{meta['namespace']}.{name}"
        model_id = node.get("attached_node")
        if model_id:
            tests.setdefault((model_id, node["column_name"]), []).append(name)
    return tests


def render(manifest: dict) -> str:
    tests = column_tests(manifest)
    lines = [
        "# Data dictionary",
        "",
        "<!-- Generated by scripts/build_data_dictionary.py from the dbt YAML. Do not edit by hand. -->",
        "",
        "Types are the logical types declared in the YAML; Snowflake and DuckDB "
        "spell some differently (`double` is `FLOAT` on Snowflake, `varchar` is "
        "`TEXT`). Intermediate models are documented in "
        "[`models/intermediate/_int__models.yml`](../models/intermediate/_int__models.yml) "
        "and in the dbt docs site (`make docs`).",
        "",
    ]
    for folder, title in LAYERS:
        models = sorted(
            (n for n in manifest["nodes"].values()
             if n["resource_type"] == "model"
             and n["package_name"] == "sec_analytics"
             and n["original_file_path"].startswith(f"models/{folder}/")),
            key=lambda n: n["name"],
        )  # fmt: skip
        if not models:
            continue
        lines += [f"## {title}", ""]
        for node in models:
            materialized = node["config"].get("materialized", "")
            lines += [
                f"### `{node['name']}`",
                "",
                f"*{materialized}* · [`{node['original_file_path']}`](../{node['original_file_path']})",
                "",
                " ".join(node.get("description", "").split()),
                "",
                "| Column | Type | Description | Tests |",
                "|---|---|---|---|",
            ]
            for column, spec in node.get("columns", {}).items():
                description = " ".join(spec.get("description", "").split()).replace("|", "\\|")
                column_test_names = ", ".join(sorted(set(tests.get((node["unique_id"], column), []))))
                lines.append(
                    f"| `{column}` | {spec.get('data_type') or ''} | {description} | {column_test_names} |"
                )
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    manifest_path = REPO_ROOT / "target" / "manifest.json"
    if not manifest_path.exists():
        sys.exit("error: target/manifest.json not found; run `dbt parse` first")
    content = render(json.loads(manifest_path.read_text(encoding="utf-8")))

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print("docs/DATA_DICTIONARY.md is out of date; run `make data-dictionary`")
            return 1
        print("docs/DATA_DICTIONARY.md is up to date.")
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
